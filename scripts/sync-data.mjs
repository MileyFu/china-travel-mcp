import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const mcpRoot = path.resolve(__dirname, '..');
const siteDataDir = path.resolve(mcpRoot, '../src/data');
const outDir = path.resolve(mcpRoot, 'src/generated');

const SOURCES = [
  'visaPolicy.ts',
  'countryVisaDossiers.ts',
  'appCompatibility.ts',
  'viralCoordinatesData.ts',
  'cityTranslatorDossiers.ts',
];

function transpileAndEvaluate(tsFilePath) {
  const sourceCode = fs.readFileSync(tsFilePath, 'utf8');
  const transpiled = ts.transpileModule(sourceCode, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
    },
    fileName: tsFilePath,
  });

  const moduleObj = { exports: {} };
  const context = vm.createContext({
    module: moduleObj,
    exports: moduleObj.exports,
    require: () => {
      throw new Error(`Unexpected require inside ${path.basename(tsFilePath)}`);
    },
  });

  const script = new vm.Script(transpiled.outputText, { filename: tsFilePath });
  script.runInContext(context);
  return moduleObj.exports;
}

function main() {
  const outTsFile = path.join(outDir, 'dataBundle.ts');
  if (!fs.existsSync(siteDataDir)) {
    if (fs.existsSync(outTsFile)) {
      console.log('Parent src/data not present; keeping existing generated dataBundle.ts');
      return;
    }
    throw new Error(`Missing source data directory at ${siteDataDir}`);
  }

  fs.mkdirSync(outDir, { recursive: true });

  const loaded = {};
  for (const file of SOURCES) {
    loaded[file] = transpileAndEvaluate(path.join(siteDataDir, file));
  }

  const bundle = {
    generatedAt: new Date().toISOString().slice(0, 10),
    countries: loaded['visaPolicy.ts'].COUNTRIES,
    ports: loaded['visaPolicy.ts'].PORTS,
    countryDossiers: loaded['countryVisaDossiers.ts'].COUNTRY_DOSSIERS.map((d) => ({
      slug: d.slug,
      code: d.code,
      name: d.name,
      demonym: d.demonym,
      flag: d.flag,
      region: d.region,
      category: d.category,
      policyTitle: d.policyTitle,
      maxStayDays: d.maxStayDays,
      maxStayHours: d.maxStayHours,
      directRoundTripAllowed: d.directRoundTripAllowed,
      thirdCountryRequired: d.thirdCountryRequired,
      policyValidity: d.policyValidity,
      executiveSummary: d.executiveSummary,
      allowedStayArea: d.allowedStayArea,
      sampleRoutes: d.sampleRoutes,
      eSIMAdvice: d.eSIMAdvice,
      specialPassportWarning: d.specialPassportWarning ?? null,
    })),
    apps: loaded['appCompatibility.ts'].APPS_DATA,
    appCategories: loaded['appCompatibility.ts'].CATEGORIES,
    viralSpots: loaded['viralCoordinatesData.ts'].VIRAL_SPOTS,
    cityFixers: loaded['cityTranslatorDossiers.ts'].CITY_TRANSLATOR_DOSSIERS,
  };

  const tsContent = `// AUTO-GENERATED by scripts/sync-data.mjs from china-nomad-guide/src/data/
// Do not edit manually. Run \`npm run sync-data\` to refresh from live site datasets.
import type { DataBundle } from '../types.js';

export const DATA_BUNDLE: DataBundle = ${JSON.stringify(bundle, null, 2)};
`;

  fs.writeFileSync(outTsFile, tsContent, 'utf8');

  console.log(
    `Synced ChinaStay MCP dataBundle.ts (${bundle.countries.length} countries, ${bundle.ports.length} ports, ${bundle.apps.length} apps, ${bundle.viralSpots.length} viral spots, ${bundle.cityFixers.length} fixer cities)`
  );
}

main();
